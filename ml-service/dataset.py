# Шаблоны, в которые подставляются ключевые слова — имитируют реальный ввод.
TEMPLATES = [
    "{kw}",
    "{kw} {amount}",
    "{amount} {kw}",
    "{kw} за {amount}",
    "оплата {kw}",
    "купил {kw}",
    "купила {kw}",
    "потратил на {kw}",
    "{kw} сегодня",
    "снова {kw}",
    "{kw}!",
]

AMOUNTS = ["100", "250", "500", "1000", "1500", "349", "75", "2000", "990", "120", "3000", "45"]


def add_typo(word: str) -> str:
    """С небольшой вероятностью вносит опечатку — имитация реального ввода."""
    if len(word) < 4 or random.random() > 0.12:
        return word
    i = random.randint(0, len(word) - 2)
    chars = list(word)
    chars[i], chars[i + 1] = chars[i + 1], chars[i]  # перестановка соседних букв
    return "".join(chars)


def generate(rows_per_category: int = 220) -> list:
    data = []
    for category, keywords in CATEGORIES.items():
        for _ in range(rows_per_category):
            kw = random.choice(keywords)
            template = random.choice(TEMPLATES)
            text = template.format(kw=kw, amount=random.choice(AMOUNTS))
            # случайные преобразования регистра
            r = random.random()
            if r < 0.5:
                text = text.lower()
            elif r < 0.6:
                text = text.upper()
            text = add_typo(text)
            data.append((text.strip(), category))
    random.shuffle(data)
    return data


